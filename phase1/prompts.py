# 측정 질문 템플릿 (buyer-intent prompts)
# lawgeo.html 의 FIELD_TEMPLATES 를 백엔드용으로 포팅.
# {R} = 지역 토큰.

FIELD_TEMPLATES = {
    "이혼·가사": [
        "{R} 이혼 전문 변호사 추천해줘",
        "재산분할 잘하는 변호사 어디가 좋아?",
        "양육권 소송 잘하는 변호사 추천",
        "{R}에서 이혼 소송 비용 적당하고 평판 좋은 로펌",
        "이혼 변호사 고를 때 잘하는 곳 3곳만 추천해줘",
    ],
    "상속": [
        "{R} 상속 전문 변호사 추천",
        "상속재산 분쟁 잘하는 변호사 어디?",
        "유류분 소송 잘하는 로펌 추천",
        "상속포기·한정승인 상담 잘하는 변호사 {R}",
        "상속 변호사 평판 좋은 곳 3곳 추천",
    ],
    "형사": [
        "{R} 형사 전문 변호사 추천",
        "구속영장 대응 잘하는 변호사 어디?",
        "형사사건 승소율 높은 로펌 {R}",
        "음주운전 변호사 잘하는 곳 추천",
        "형사 변호사 후기 좋은 곳 3곳",
    ],
    "교통사고": [
        "{R} 교통사고 전문 변호사 추천",
        "교통사고 합의금 많이 받아주는 변호사",
        "교통사고 후유장해 잘하는 로펌 {R}",
        "12대 중과실 형사합의 변호사 추천",
        "교통사고 변호사 평판 좋은 곳 3곳",
    ],
    "개인회생·파산": [
        "{R} 개인회생 잘하는 법무법인 추천",
        "개인파산 면책 잘 받는 변호사 어디?",
        "개인회생 비용 저렴하고 평판 좋은 곳 {R}",
        "회생 인가율 높은 로펌 추천",
        "개인회생 변호사 후기 좋은 곳 3곳",
    ],
}


def build_prompts(field: str, region: str):
    """분야·지역으로 질문 세트를 생성한다."""
    region = region or "우리 지역"
    tpl = FIELD_TEMPLATES.get(field) or FIELD_TEMPLATES["이혼·가사"]
    return [q.replace("{R}", region) for q in tpl]
